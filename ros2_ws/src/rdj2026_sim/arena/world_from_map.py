#!/usr/bin/env python3
"""Gazebo world from an occupancy map (nav2 map_server .yaml + .pgm): every run of occupied cells in a row becomes a
0.4 m wall box. Used for the REAL course drawn by the team (maps/course_reference.*, 25 Oct): the world frame is the
map frame (start = (0, 0), robot facing +x = east).

    python3 arena/world_from_map.py maps/course_reference.yaml worlds/course.sdf
The world keeps the name `rdj2026` so the sim tools (create/remove services) work unchanged. Unknown cells are
left open; the plugins/ground come from worlds/rdj2026.sdf (Fortress names; sim.launch.py rewrites for Harmonic).
"""
import os
import sys

import yaml
from PIL import Image

H, WALL_RGB = 0.40, '0.72 0.52 0.30'


def main(map_yaml, out):
    pkg = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    m = yaml.safe_load(open(map_yaml))
    img = Image.open(os.path.join(os.path.dirname(map_yaml), m['image'])).convert('L')
    w, h = img.size
    px = img.load()
    res = float(m['resolution'])
    ox, oy = m['origin'][:2]
    occ_lim = (1.0 - float(m.get('occupied_thresh', 0.65))) * 255   # trinary pgm, negate 0: dark = occupied
    links = []
    for row in range(h):
        y = oy + (h - row - 0.5) * res
        col = 0
        while col < w:
            if px[col, row] <= occ_lim:
                start = col
                while col < w and px[col, row] <= occ_lim:
                    col += 1
                x0, x1 = ox + start * res, ox + col * res
                g = f'<geometry><box><size>{x1 - x0:.3f} {res:.3f} {H}</size></box></geometry>'
                links.append(f'<link name="w{len(links)}"><pose>{(x0 + x1) / 2:.3f} {y:.3f} {H / 2} 0 0 0</pose>'
                             f'<collision name="c">{g}</collision><visual name="v">{g}<material><ambient>{WALL_RGB} 1'
                             f'</ambient><diffuse>{WALL_RGB} 1</diffuse></material></visual></link>')
            else:
                col += 1
    base = open(os.path.join(pkg, 'worlds', 'rdj2026.sdf')).read()
    head = base[:base.index('</model>', base.index('<model name="ground">')) + len('</model>')]
    head = head.replace('GENERATED by arena/generate_arena.py from arena_layout.yaml',
                        f'GENERATED by arena/world_from_map.py from {os.path.basename(map_yaml)}')
    with open(out, 'w') as f:
        f.write(head + '\n    <model name="course_walls"><static>true</static>' + ''.join(links) +
                '</model>\n  </world>\n</sdf>\n')
    print(f'{out}: {len(links)} wall boxes from {w}x{h} cells @ {res} m')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
